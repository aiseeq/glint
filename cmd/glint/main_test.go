func TestSuppressionWithoutReasonUsesCommentSyntaxAndSeparators(t *testing.T) {
	source := "package app\nconst example = `//nolint:error-wrap\n// error-wrap: safe`\n// nolint:error-wrap -- explained\n// nolint:error-wrap - explained\n// nolint:error-wrap — explained\n// nolint:error-wrap: explained\n// nolint:error-wrap explained\n// nolint:error-wrap --\n// nolint:foreign,error-wrap\n//nolint:magic-number\n// any-in-public-contract: safe\n// any-in-public-contract: safe -- explained\n"
	root := t.TempDir()
	path := filepath.Join(root, "example.go")
	ctx := parsedGoContext(t, path, root, source)
	found := deadcode.NewSuppressionWithoutReasonRule().AnalyzeFile(ctx)
	var lines []int
	for _, violation := range found {
		lines = append(lines, violation.Line)
	}
	if !reflect.DeepEqual(lines, []int{9, 10, 11, 12}) {
		t.Fatalf("unexpected findings at %v", lines)
	}
}

func parsedGoContext(t *testing.T, path, root, source string) *core.FileContext {
	t.Helper()
	cfg := core.DefaultConfig()
	ctx := core.NewFileContext(path, root, []byte(source), cfg)
	fset := token.NewFileSet()
	parsed, err := parser.ParseFile(fset, path, source, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	ctx.GoAST, ctx.GoFileSet = parsed, fset
	return ctx
}

func TestBroadExclusionFindings(t *testing.T) {
	root := t.TempDir()
	write := func(name, text string) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write(".glint.yaml", "settings:\n  exclude:\n    - internal/**\n    - testdata/**\ncategories:\n  naming:\n    enabled: false\n  patterns:\n    rules:\n      error-wrap:\n        exceptions:\n          - files: pkg/**\n            reason: applies only in this package\n      context-first:\n        exceptions:\n          - files: \"**\"\n            reason: everywhere\n")
	write("internal/store/store.go", "package store\n")
	write("pkg/api/api.go", "package api\n")
	write("testdata/example.go", "package example\n")
	write("generated/only.go", "// Code generated by fixture. DO NOT EDIT.\npackage generated\n")
	cfg, err := core.LoadConfigWithDefaults(root)
	if err != nil {
		t.Fatal(err)
	}
	ctx := core.NewFileContext(filepath.Join(root, "pkg/api/api.go"), root, []byte("package api\n"), cfg)
	found := broadFindingsForTest(t, cfg, []*core.FileContext{ctx})
	// A directory exempted from one rule (pkg/**) is narrower than switching
	// the rule off; a glob over the whole project (**) for one rule is not.
	if len(found) != 3 || found[0].Line != 3 || found[1].Line != 16 || found[2].Line != 7 {
		t.Fatalf("unexpected broad exclusions: %#v", found)
	}
}

