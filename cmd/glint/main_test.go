func TestBroadExclusionSkipsUnreadableDirectory(t *testing.T) {
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, ".glint.yaml"), []byte("settings:\n  exclude:\n    - studies/**\n"), 0644); err != nil {
		t.Fatal(err)
	}
	for _, dir := range []string{"studies", "pkg", "pgdata"} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(root, "studies/a.go"), []byte("package studies\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "pkg/b.go"), []byte("package pkg\n"), 0644); err != nil {
		t.Fatal(err)
	}
	// A database volume owned by another user: the walk cannot enter it.
	locked := filepath.Join(root, "pgdata")
	if err := os.Chmod(locked, 0); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(locked, 0755) })
	if _, err := os.ReadDir(locked); err == nil {
		t.Skip("running with permission to read a mode 000 directory")
	}
	cfg, err := core.LoadConfigWithDefaults(root)
	if err != nil {
		t.Fatal(err)
	}
	ctx := core.NewFileContext(filepath.Join(root, "pkg/b.go"), root, []byte("package pkg\n"), cfg)
	found, err := broadExclusionFindings(cfg, []*core.FileContext{ctx})
	if err != nil {
		t.Fatalf("unreadable directory failed the check: %v", err)
	}
	if len(found) != 1 || found[0].Line != 3 {
		t.Fatalf("unexpected broad exclusions: %#v", found)
	}
}
