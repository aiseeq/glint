package frontendrules

import (
	"testing"

	"github.com/aiseeq/glint/pkg/core"
	"github.com/aiseeq/glint/pkg/rules/rulestest"
	"github.com/stretchr/testify/assert"
)

func configuredPeriodBoundaryRule(t *testing.T) *TSPeriodBoundaryByHandRule {
	t.Helper()
	rule := NewTSPeriodBoundaryByHandRule()
	assert.NoError(t, rule.Configure(map[string]any{"period_modules": []any{"web/lib/period.ts"}}))
	return rule
}

func periodBoundaryPlaces(t *testing.T, rule *TSPeriodBoundaryByHandRule, files map[string]string) []string {
	t.Helper()
	_, contexts := rulestest.Module(t, files)
	rule.ResetState()
	rule.UseProjectFiles(contexts)
	var violations []*core.Violation
	for _, ctx := range contexts {
		violations = append(violations, rule.AnalyzeFile(ctx)...)
	}
	return rulestest.ViolationPlaces(violations)
}

func TestTSPeriodBoundaryByHand(t *testing.T) {
	files := map[string]string{
		"web/lib/period.ts": `export function periodStart() { return new Date() }`,
		"web/Stats.tsx": `const from = new Date(); from.setDate(from.getDate() - 7)
const monthStart = new Date(now.getFullYear(), now.getMonth(), 1)
date.setUTCMonth(date.getUTCMonth() + 1)
date.setFullYear(date.getFullYear() - 1)
date.setHours(0, 0, 0, 0)`,
	}
	assert.Equal(t, []string{"web/Stats.tsx:1", "web/Stats.tsx:2", "web/Stats.tsx:3", "web/Stats.tsx:4", "web/Stats.tsx:5"}, periodBoundaryPlaces(t, configuredPeriodBoundaryRule(t), files))
}

func TestTSPeriodBoundaryByHandNegatives(t *testing.T) {
	files := map[string]string{
		"web/Stats.test.ts":     `date.setDate(date.getDate() - 7)`,
		"web/e2e/stats.spec.ts": `date.setDate(date.getDate() - 7)`,
		"web/lib/generated/stats.ts": `// Code generated by fixture. DO NOT EDIT.
date.setDate(date.getDate() - 7)`,
		"web/Stats.tsx": `const d = new Date(row.createdAt)
const t = new Date(Date.now() + 5000)`,
	}
	assert.Empty(t, periodBoundaryPlaces(t, configuredPeriodBoundaryRule(t), files))

	rule := NewTSPeriodBoundaryByHandRule()
	assert.NoError(t, rule.Configure(map[string]any{}))
	assert.Empty(t, periodBoundaryPlaces(t, rule, map[string]string{
		"web/Stats.tsx": `date.setDate(date.getDate() - 7)`,
	}))
}

func TestTSPeriodBoundaryByHandModuleItself(t *testing.T) {
	files := map[string]string{
		"web/lib/period.ts": `export function periodStart() {
 const start = new Date(now.getFullYear(), now.getMonth(), 1)
 start.setDate(start.getDate() - 7)
 return start
}`,
		"web/Stats.tsx": `const from = new Date(); from.setDate(from.getDate() - 7)`,
	}
	assert.Equal(t, []string{"web/Stats.tsx:1"}, periodBoundaryPlaces(t, configuredPeriodBoundaryRule(t), files))
}

func TestTSPeriodBoundaryByHandBadConfig(t *testing.T) {
	for _, setting := range []any{"web/lib/period.ts", []any{"web/lib/period.ts", 7}, []any{" "}} {
		rule := NewTSPeriodBoundaryByHandRule()
		assert.Error(t, rule.Configure(map[string]any{"period_modules": setting}))
	}
}

func TestTSPeriodBoundaryByHandDayDifference(t *testing.T) {
	files := map[string]string{
		"web/lib/period.ts": `export const DAY_MS = 86_400_000`,
		"web/Stats.tsx": `const days = Math.round((day(now) - day(at)) / 86_400_000)
const left = Math.round((day(to) - day(now)) / 864e5)
const n = Math.floor((b.getTime() - a.getTime()) / (24 * 60 * 60 * 1000))
const custom = Math.trunc((end - start) / DAY_MS)
const ms = Date.now() - start
const pct = Math.round((done - total) / 1000)`,
	}
	assert.Equal(t, []string{"web/Stats.tsx:1", "web/Stats.tsx:2", "web/Stats.tsx:3", "web/Stats.tsx:4"}, periodBoundaryPlaces(t, configuredPeriodBoundaryRule(t), files))
}
