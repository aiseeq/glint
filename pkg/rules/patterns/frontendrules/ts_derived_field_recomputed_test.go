package frontendrules

import (
	"github.com/aiseeq/glint/pkg/rules/rulestest"
	"github.com/stretchr/testify/assert"
	"testing"
)

func TestTSDerivedFieldRecomputed(t *testing.T) {
	files := map[string]string{"types/generated.ts": `// Code generated by typegen. DO NOT EDIT.
export interface Withdrawal { status: string; holdState?: string; statusGroup: string; amount: string }`, "lib/withdrawal.ts": `export function displayStatus(w: Withdrawal): string {
 if (w.status === 'cancelled' || w.holdState === 'cancelled') return 'cancelled'
 if (w.status === 'pending' || w.status === 'approved') return 'pending'
 return 'done'
 }`}
	files["lib/cases.ts"] = `function fromCases(w: Withdrawal) {
 switch (w.status) {
 case 'pending': return 1
 case 'approved': return 2
 }
}
function fromList(w: Withdrawal) {
 return ['pending', 'approved'].includes(w.status)
}`
	assert.Equal(t, []string{"lib/cases.ts:2", "lib/cases.ts:8", "lib/withdrawal.ts:2"}, rulestest.ProjectFilesRulePlaces(t, NewTSDerivedFieldRecomputedRule(), files))
}
func TestTSDerivedFieldRecomputedStructural(t *testing.T) {
	files := map[string]string{
		"types/generated.ts": `export interface PayoutWithUser { id: string; status: string; holdState?: string | null; statusGroup: string }`,
		"lib/payout-utils.ts": `export function resolvePayoutDisplayStatus(p: { status: string; holdState?: string | null }): string {
 if (p.holdState === 'cancelled') return 'cancelled'
 if (p.status === 'failed' || p.status === 'rejected') return 'failed'
 return p.status
}`,
		"lib/payout-status.ts": `type Key = string
export function payoutStatusKey(status: string, holdState?: string | null): Key {
 if (holdState === 'cancelled') return 'cancelled'
 if (status === 'completed' || status === 'confirmed') return 'sent'
 if (status === 'pending') return 'pending'
 return 'unknown'
}
function unrelated(status: string, kind: string) {
 if (status === 'completed' || status === 'confirmed') return kind
}`,
	}
	assert.Equal(t, []string{"lib/payout-status.ts:4", "lib/payout-utils.ts:3"}, rulestest.ProjectFilesRulePlaces(t, NewTSDerivedFieldRecomputedRule(), files))
}

func TestTSDerivedFieldRecomputedNegatives(t *testing.T) {
	files := map[string]string{"types/model.ts": `interface State { status: string; statusCategory: string }
 function sameFile(w: State) { return w.status === 'pending' || w.status === 'done' }`, "src/view.ts": `function readsGroup(w: State) { return w.statusCategory }
 function oneValue(w: State) { return w.status === 'pending' }
 function noDerived(w: Plain) { return w.status === 'pending' || w.status === 'done' }`, "src/view.test.ts": `function test(w: State) { return w.status === 'a' || w.status === 'b' }`}
	assert.Empty(t, rulestest.ProjectFilesRulePlaces(t, NewTSDerivedFieldRecomputedRule(), files))
}
