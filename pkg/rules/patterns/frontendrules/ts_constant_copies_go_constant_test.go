package frontendrules

import (
	"testing"

	"github.com/aiseeq/glint/pkg/rules/rulestest"
	"github.com/stretchr/testify/assert"
)

func TestTSConstantCopiesGoConstant(t *testing.T) {
	files := map[string]string{
		"models/goal.go": `package models
const (
 UserGoalNameMaxLength = 40
 UserGoalMaxAmount = "1000000000"
 MaxUserGoals = 3
)
`,
		"web/GoalForm.tsx": `export const GOAL_NAME_MAX = 40
export const GOAL_AMOUNT_MAX = 1e9
const PAGE_SIZE = 40
const GOAL_NAME_MAX_OLD = 50
`,
	}
	assert.Equal(t, []string{"web/GoalForm.tsx:1", "web/GoalForm.tsx:2"}, rulestest.ProjectFilesRulePlaces(t, NewTSConstantCopiesGoConstantRule(), files))
}

func TestTSConstantCopiesGoConstantNegatives(t *testing.T) {
	files := map[string]string{
		"models/limits.go": `package models
const (
 UserGoalNameMaxLength = 40
 UserGoalMaxAmount = "1000000000"
 UnrelatedLimit = 7
)
`,
		"models/limits_test.go": `package models
const TestGoalNameMaxLength = 40
`,
		"models/generated.go": `// Code generated by tool. DO NOT EDIT.
package models
const GeneratedGoalMaxLength = 40
`,
		"web/negative.ts": `const GOAL_NAME_MAX = 1
const GOAL_COUNT = 40
const GOAL_NAME_MAX = 41
function build() {
  const GOAL_NAME_MAX = 40
}
`,
		"web/generated/limits.ts": `export const USER_GOAL_NAME_MAX_LENGTH = 40
`,
		"web/test/e2e/limits.ts": `export const USER_GOAL_NAME_MAX_LENGTH = 40
`,
		"web/node_modules/pkg/limits.ts": `export const USER_GOAL_NAME_MAX_LENGTH = 40
`,
	}
	assert.Empty(t, rulestest.ProjectFilesRulePlaces(t, NewTSConstantCopiesGoConstantRule(), files))
}
